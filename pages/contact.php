          <h2>If a time was wrong</h2>
          <p>Tell us how long it actually took and where the time went. The
            most common answer is the pan: a recipe timed in a 28 cm pan over a
            high flame takes noticeably longer in a small one on an electric
            ring, and if several people report the same gap we re-time it and
            change the number.</p>
          <p>This has happened once. The chilli paneer was published at twelve
            minutes and is now fifteen, because three readers in a row said the
            paneer took longer to colour than we had allowed for.</p>

          <h2>The most useful thing you can send</h2>
          <p>A timing. If you cooked something here and it took you eleven
            minutes or twenty-six, that number is worth more to us than any
            other kind of feedback, because it is the one claim this whole site
            rests on and we can only test it on our own hob.</p>
          <p>Include the pan you used and whether your hob is gas, electric or
            induction. Induction in particular is fast enough to change a
            recipe by two or three minutes, and we time on gas.</p>

          <h2>Suggesting a recipe</h2>
          <p>Welcome, and the useful version of the suggestion is a dish plus
            a reason to believe it can be done in the time. "Something with
            aubergine" is hard to act on; "aubergine is the one vegetable I
            cannot make fast" is a real brief and is currently being worked
            on.</p>
          <p>We cannot promise to get to any of them, and a suggestion that
            cannot be brought under twenty minutes will not go up however good
            it is. That has happened three times so far.</p>

          <h2>What we cannot help with</h2>
          <p>Whether a recipe suits a medical diet, exact nutrition for your
            version, or allergy advice. Our figures are estimates and our
            allergen notes cover the recipe as written &mdash; the reasons are
            in the <a href="../policies/disclaimer.php">disclaimer</a> and they
            are worth reading if you cook for someone with an allergy.</p>
          <p>We do not accept guest posts, sponsored recipes or link requests,
            and those emails are deleted without a reply. If you are writing to
            offer us a "content partnership", the answer is no and it will stay
            no; the reasoning is set out in full on the
            <a href="../policies/advertising-disclosure.php">advertising
            disclosure</a> page.</p>
          <p>We also cannot convert recipes to an air fryer, a slow cooker or a
            multi-cooker for you. Several of these would work in one and we
            have simply not tested them that way, and publishing an untested
            time on a site whose entire proposition is accurate times would be
            self-defeating.</p>

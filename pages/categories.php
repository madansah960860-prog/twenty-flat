          <h2>The pantry list</h2>
          <p>Nine things. Keep them in and three of the six recipes on this
            site need no shopping at all, which is the entire point of a
            pantry.</p>
          <ul>
            <li><strong>Dried noodles or spaghetti</strong> &mdash; unlocks the
              garlic butter noodles on its own.</li>
            <li><strong>Tinned chickpeas, two tins</strong> &mdash; chana
              masala.</li>
            <li><strong>Tinned white beans</strong> and <strong>tinned tuna in
              olive oil</strong> &mdash; the salad, with no cooking at all.</li>
            <li><strong>Tinned chopped tomatoes</strong> &mdash; the base of
              the chana masala and useful in everything else.</li>
            <li><strong>Soy sauce</strong>, <strong>rice or red wine
              vinegar</strong> and <strong>toasted sesame oil</strong> &mdash;
              between them these three season four of the six.</li>
            <li><strong>Garlic and onions</strong>, always. Every recipe here
              starts with one or both.</li>
          </ul>
          <p>Everything else on this site is one shop-bought fresh item away:
            a block of paneer, a packet of gnocchi, a bag of spinach.</p>
        </div>
        <div class="prose">
          <h2>What actually makes food fast</h2>
          <p>Not skill, and not gadgets. Three things, in order of how much
            time they save.</p>
          <p><strong>A wide pan on a high heat.</strong> Most home cooking is
            slow because the pan is too small and too cool, so food steams in
            its own liquid instead of browning. A 28 cm pan preheated properly
            does in five minutes what a crowded 20 cm pan does in twenty.</p>
          <p><strong>Reading the recipe first.</strong> Genuinely. Almost every
            recipe here has a step that happens while something else cooks, and
            that overlap is where the time goes if you discover it too
            late.</p>
          <p><strong>Not chopping things you do not need to chop.</strong>
            Onion petals instead of dice, torn herbs instead of chopped, garlic
            sliced instead of crushed. None of it changes the dish and it saves
            three or four minutes every time.</p>
        </div>
      </div>

        <h2>The twenty-minute ceiling</h2>
        <p>Twenty minutes is a real ceiling here, not a marketing one. A recipe
          that comes in at twenty-three minutes does not go on the site, and
          three have been rejected for exactly that: a harissa chickpea
          flatbread that will not go under twenty-two, a laksa that was never
          going to make it, and a mushroom risotto that was frankly optimistic
          to have tried.</p>
        <p>The ceiling exists because a site called Twenty Flat that publishes
          thirty-five-minute recipes is lying to the person reading it, and
          because the constraint genuinely improves the cooking. Almost every
          recipe here got better when it got faster.</p>

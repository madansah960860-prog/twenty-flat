          <h2>How the filter works</h2>
          <p>There is no JavaScript on this site at all. The filter is four
            empty anchors and a handful of CSS rules using the <code>:target</code>
            pseudo-class: clicking "10 min" puts <code>#t10</code> in the
            address bar, and a stylesheet rule hides every recipe that is not
            tagged as a ten-minute one.</p>
          <p>The practical benefit is that the filtered view is a real URL. You
            can bookmark it, send it to somebody, or open it on your phone on
            the bus home, and it works with the browser back button because it
            is just an anchor.</p>
        </div>
        <div class="prose">
          <h2>Why only six</h2>
          <p>Because each of these has been cooked and timed at least five
            times, twice by somebody who did not write it, and a recipe that
            comes in at twenty-three minutes does not go on a site called
            Twenty Flat.</p>
          <p>Four more are being timed: a black bean quesadilla that is
            currently eleven minutes, a miso butter salmon at twelve, a
            harissa chickpea flatbread that keeps coming in at twenty-two and
            may not make it, and a proper five-minute dressing that turns any
            bag of leaves into dinner.</p>
          <h2>Three of these need no shopping</h2>
          <p>The noodles, the chana masala and the tuna bean salad are built
            entirely from things that live in a cupboard. If you keep the nine
            items on the <a href="categories.php">by time page</a> in, you can
            cook one of those three on any evening without having thought about
            it in advance, which is the actual definition of a weeknight
            recipe.</p>

          <h2>Reading a recipe before you start</h2>
          <p>Every recipe on this site is written so the whole thing fits on
            one screen without scrolling past the method, and the ingredients
            sit beside the steps rather than above them. That is deliberate:
            at ten past six you are reading with one hand and a knife in the
            other.</p>
          <p>The single most useful thing you can do is read the six or seven
            steps through once before you touch anything. Two minutes spent
            doing that is where the difference between the published time and
            your time usually lives.</p>
        </div>

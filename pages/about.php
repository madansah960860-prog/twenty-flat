          <h2>Who writes it</h2>
          <p>Marco Vasquez-Reid cooked in restaurants for nine years, mostly on
            the pass at a mid-sized Manchester bistro, and then stopped in 2022
            because the hours were incompatible with having a child. Twenty
            Flat started as a list stuck to his own fridge.</p>
          <p>The name is the rule &mdash; twenty minutes, flat &mdash; and the site exists because
            almost every "quick" recipe he found in that first year was not
            quick. Thirty-five minutes is not quick. Twenty is.</p>

          <h2>How the times are measured</h2>
          <p>Stopwatch, started when the first ingredient is picked up, stopped
            when the food is on a plate. No pre-chopped anything. No assuming
            the oven is already hot &mdash; if a recipe needs a preheat, the
            preheat is inside the time.</p>
          <p>Every recipe is timed at least five times, and at least twice by
            somebody who did not write it, because the person who invented a
            dish is always faster at it than everybody else. The published
            number is the slowest of those runs rounded up, not the fastest.</p>

          <h2>What gets rejected</h2>
          <p>Three recipes have been cut for going over: a harissa chickpea
            flatbread stuck at twenty-two minutes, a laksa that was never
            realistic, and a mushroom risotto. All three were good. None of
            them belongs on this site.</p>
        </div>
        <div class="prose">
          <h2>What this site will not tell you</h2>
          <p>That any of this is healthy, clean, or good for you in some
            specific measurable way. These are weeknight dinners. Several of
            them contain a great deal of butter, and the nutrition figures on
            every recipe are clearly labelled as estimates.</p>
          <p>It will also never pretend a shortcut is as good as the long
            version when it is not. The fifteen-minute chana masala says
            plainly, on its own page, what you lose compared with the two-hour
            one and why.</p>

          <h2>The kitchen it is tested in</h2>
          <p>A galley kitchen in a Manchester flat with four gas rings, one
            elderly fan oven and about ninety centimetres of worktop. That is
            deliberate. A recipe timed in a professional kitchen with three
            metres of bench and a salamander is not a twenty-minute recipe in
            anybody else's house.</p>
          <p>The equipment that matters is a 28 cm frying pan, one large
            saucepan, one baking tray and a sharp knife. Nothing on this site
            needs a food processor, a blender, an air fryer or a scale that
            weighs to the gram.</p>

          <h2>Money</h2>
          <p>Display advertising, and nothing else. No affiliate links
            anywhere, no sponsored recipes, no brand partnerships, and nothing
            for sale. Two supermarkets and a pasta brand have asked about
            "content collaborations" and all three were declined. The detail is
            on the
            <a href="../policies/advertising-disclosure.php">advertising
            disclosure</a> page.</p>

          <h2>Corrections</h2>
          <p>One so far: the egg fried rice originally said the rice could be
            "cooled and used the same day", which understated the food-safety
            point about cooling rice quickly. It was rewritten within a day of
            a reader pointing it out and the change is noted on the page.</p>
          <p>If something here does not work, or a time is wrong for you, email
            <a href="mailto:hello@twentyflat.kitchen">hello@twentyflat.kitchen</a>.</p>

        <div>
          <h2>Method</h2>
          <ol class="method"><li><p>Put the noodles on to boil in well-salted water. Set a timer for one minute less than the packet says. Everything else happens while they cook.</p></li><li><p>Melt the butter in a wide cold pan over a low heat. Add the garlic before the butter is hot &mdash; starting it cold is the whole trick, because sliced garlic dropped into hot butter burns in under a minute.</p></li><li><p>Cook the garlic gently for 3&ndash;4 minutes, swirling, until it is pale gold and the butter smells sweet. Add the chilli flakes for the last 20 seconds.</p></li><li><p>Stir in the soy sauce and sugar. It will spit. Take it off the heat.</p></li><li><p>Drain the noodles, keeping a mugful of the water. Tip the noodles into the pan with two tablespoons of that water and toss hard for 30 seconds until every strand is glossy and there is no loose butter in the base.</p></li><li><p>Add more noodle water a splash at a time if it looks dry. Scatter the spring onion and sesame over the top and eat it standing up if necessary.</p></li></ol>
        </div>
      </div>

      <div class="panel">
        <h3>The one thing that goes wrong</h3>
        <p>Burnt garlic. It happens in the ten seconds you spend draining the noodles, and there is no fixing it &mdash; burnt garlic is bitter all the way through the dish. Start it in cold butter, keep the heat genuinely low, and take the pan off before you touch the colander.</p>
      </div>


        <div>
          <h2>Method</h2>
          <ol class="method"><li><p>Heat the oil in a wide pan over a high heat. Add the onion with the salt and fry hard for 5 minutes, stirring often. You want real colour, and a wide pan and a high heat are how you get it in five minutes instead of fifteen.</p></li><li><p>Add the garlic and ginger and cook for 45 seconds.</p></li><li><p>Turn the heat down to medium. Add the cumin, coriander, turmeric and chilli and stir for 30 seconds &mdash; no longer, ground spice burns fast.</p></li><li><p>Add the tomatoes and the water. Turn the heat back up and cook for 4 minutes, squashing the tomatoes against the side of the pan, until the sauce darkens and the oil starts to separate at the edges.</p></li><li><p>Add the chickpeas. Crush about a quarter of them against the pan with the back of a spoon &mdash; that is what thickens the sauce without any simmering time.</p></li><li><p>Cook for 4 minutes more. Stir in the garam masala and the amchur off the heat, taste for salt, and serve with rice or flatbread.</p></li></ol>
        </div>
      </div>

      <div class="panel">
        <h3>What you lose at fifteen minutes</h3>
        <p>A long-cooked chana masala is deeper because the onions have an hour to break down and the chickpeas have time to absorb the sauce. This version gets about eighty per cent of the way there with two shortcuts: a very hot wide pan to colour the onions fast, and crushing some of the chickpeas so the starch thickens the sauce immediately. It is not the same dish. It is a very good Tuesday.</p>
      </div>


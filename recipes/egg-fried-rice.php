        <div>
          <h2>Method</h2>
          <ol class="method"><li><p>Break the cold rice up with wet hands before you start. Any clumps left now will still be clumps at the end.</p></li><li><p>Get a wok or your widest frying pan genuinely hot over a high heat &mdash; hot enough that a drop of water vanishes on contact. Add 1 tbsp of the oil.</p></li><li><p>Pour in the eggs and let them set for 10 seconds, then scramble them hard for 20 seconds until just barely cooked. Tip them straight out onto a plate; they will finish cooking in the residual heat.</p></li><li><p>Add the remaining oil, then the garlic, ginger and spring onion whites. Stir for 20 seconds only.</p></li><li><p>Add the rice and the frozen peas. Now stop stirring: press the rice into the pan and leave it for 45 seconds at a time, three or four times over, so it catches and crisps rather than steams.</p></li><li><p>Return the egg, breaking it up. Add the soy, sesame oil and white pepper and toss everything together for 30 seconds.</p></li><li><p>Off the heat, stir through the spring onion greens. Taste &mdash; it usually wants a little more soy than you think.</p></li></ol>
        </div>
      </div>

      <div class="panel">
        <h3>Why the rice has to be cold</h3>
        <p>Freshly cooked rice is full of surface moisture and the starch has not retrograded, so it steams in the pan and collapses into paste. Chilling overnight firms the grains and dries the surface, which is why they separate and crisp instead. If you have no cold rice, spread hot rice on a tray and put it in the freezer for 20 minutes.</p>
      </div>


        <div>
          <h2>Method</h2>
          <ol class="method"><li><p>Put the sliced onion in a bowl with the vinegar and a pinch of the salt. Leave it there while you do everything else &mdash; ten minutes is enough to take the raw edge off and turn it pink.</p></li><li><p>Drain and rinse the beans properly. The liquid in the tin tastes of tin, and rinsing is the difference between this tasting homemade and tasting like a tin.</p></li><li><p>Tip the beans into a wide bowl. Add the olive oil, the reserved tuna oil, the lemon zest and half the juice, and crush about a fifth of the beans against the side of the bowl with a fork. That makes the dressing cling.</p></li><li><p>Add the tuna in large flakes rather than shredding it. Add the capers, the parsley and the onion with its vinegar.</p></li><li><p>Fold it together twice, no more. Taste, add the rest of the lemon juice if it needs it, and a lot of black pepper.</p></li><li><p>Let it sit for five minutes if you can. It is better at room temperature than straight from the fridge.</p></li></ol>
        </div>
      </div>

      <div class="panel">
        <h3>Buy the tuna in oil</h3>
        <p>Tuna in brine is drier, blander and its liquid is no use to anybody. Tuna in olive oil gives you the fish and three tablespoons of seasoned oil that goes straight into the dressing, which is most of the flavour here. It costs about forty pence more.</p>
      </div>


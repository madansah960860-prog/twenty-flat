        <div>
          <h2>Method</h2>
          <ol class="method"><li><p>Heat the oven to 220&deg;C fan / 240&deg;C conventional / 425&deg;F and put your largest baking tray in it to get hot. A cold tray is the difference between roasted gnocchi and steamed gnocchi.</p></li><li><p>Tip the gnocchi straight from the packet into a bowl &mdash; do not boil them first. Add the tomatoes, onion, oil, garlic, oregano, chilli and salt and toss.</p></li><li><p>Pull the hot tray out and tip everything onto it in one layer. It should sizzle. Spread it out so nothing is touching; use two trays if you need to.</p></li><li><p>Roast for 15 minutes, shaking the tray once at the halfway point. The gnocchi should be blistered and golden and the tomatoes should have burst.</p></li><li><p>Take the tray out, squeeze the soft garlic out of its skins and mash it into the tomatoes. Add the spinach and toss it through &mdash; the residual heat wilts it in about 30 seconds.</p></li><li><p>Scatter over the cheese and the basil and serve straight from the tray.</p></li></ol>
        </div>
      </div>

      <div class="panel">
        <h3>Do not boil the gnocchi</h3>
        <p>Every packet tells you to boil them for two minutes. Do not. Boiled gnocchi are saturated with water and will never crisp, however hot the oven. Going in dry, they hydrate from the inside while the outside dries and browns, which is how you get a crust and a soft middle at the same time.</p>
      </div>


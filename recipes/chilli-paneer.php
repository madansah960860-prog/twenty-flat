        <div>
          <h2>Method</h2>
          <ol class="method"><li><p>Pat the paneer completely dry, then toss it in the cornflour until every face is dusted. Do this first and leave it while the pan heats.</p></li><li><p>Heat 2 tbsp of the oil in a wide non-stick pan over a high heat. Fry the paneer in a single layer, 60&ndash;90 seconds a side, until it is properly golden on at least three faces. Lift it out onto kitchen paper.</p></li><li><p>Add the last tablespoon of oil. Throw in the onion and pepper and fry for 2 minutes over the highest heat you have. You want them blistered at the edges and still crunchy in the middle.</p></li><li><p>Add the garlic, ginger and green chilli and stir for 30 seconds.</p></li><li><p>Mix the soy, ketchup, chilli sauce, vinegar and water in a mug and pour it in. It will hiss and thicken in about a minute.</p></li><li><p>Return the paneer and toss for 30 seconds so every piece is coated. Serve immediately &mdash; the crust softens within about four minutes.</p></li></ol>
        </div>
      </div>

      <div class="panel">
        <h3>Cornflour, not batter</h3>
        <p>A wet batter needs deep oil and two minutes you do not have. A dry cornflour dusting does the same job in a shallow pan: the starch gelatinises against the hot surface and forms a thin crisp shell, and it also thickens the sauce slightly when the paneer goes back in. Dry paneer is essential &mdash; damp paneer steams the coating off.</p>
      </div>


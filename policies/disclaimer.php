          <h1>Disclaimer</h1>
          <p class="%(L)s">Please read this before cooking from the site. Our nutrition numbers are calculated estimates, our allergen notes are general, and the responsibility for what ends up on your table is yours.</p>
          <p><strong>Effective date:</strong> %(EFF)s.</p>

          <h2>Nutrition figures are estimates</h2>
          <p>Every nutrition panel on this site is labelled as an estimate
            because that is exactly what it is. The figures are calculated from
            standard food composition databases using the ingredients and
            quantities as written, then divided by the stated number of
            servings. They are not laboratory analyses of a cooked dish.</p>
          <p>Real figures will differ from ours, sometimes considerably, for
            reasons entirely outside our control: the fat content of the meat
            you bought, the size of your onion, how much oil stayed in the pan,
            how generous your idea of &ldquo;a serving&rdquo; is, the brand of
            stock, whether your yoghurt is full-fat, and how much liquid boiled
            away in your kitchen versus ours. Where a recipe says &ldquo;season
            to taste&rdquo; or &ldquo;oil for frying&rdquo;, the calculation has
            to assume an amount, and yours will be different.</p>
          <p>If you are counting nutrients for a medical reason &mdash;
            diabetes, kidney disease, coeliac disease, a controlled-sodium diet,
            a weight-management programme supervised by a clinician &mdash; do
            not rely on our numbers. Calculate from the actual products in your
            own cupboard, and follow the advice of your dietitian or doctor over
            anything published here. Nothing on this site is medical or dietetic
            advice, and no recipe here is designed to treat or manage any
            condition.</p>

          <h2>Allergens are your responsibility</h2>
          <p>We flag the common allergens we can see in a recipe as written
            &mdash; gluten, dairy, egg, nuts, peanuts, soy, sesame, fish,
            shellfish, celery, mustard, lupin, sulphites &mdash; as a courtesy
            and a starting point. That note is not a safety guarantee and it
            cannot be one.</p>
          <p>Allergens hide in processed ingredients and change without warning:
            stock cubes, curry pastes, soy sauce, miso, mustard, vinegars,
            chocolate, baking powder, dried fruit, spice blends and
            &ldquo;natural flavouring&rdquo; are all common culprits. Recipes
            are also frequently adapted &mdash; a substitution you make, or one
            we suggest, may introduce an allergen the original did not contain.
            Shared production lines mean a product with no allergen in its
            ingredients list may still carry a &ldquo;may contain&rdquo;
            warning.</p>
          <p><strong>If you or anyone you are cooking for has a food allergy or
            intolerance, read the label on every product you use, every time you
            buy it.</strong> The packet in your hand is the authority. If a
            reaction is severe, treat every unfamiliar recipe as unsafe until
            you have checked it yourself, and speak to your allergy specialist
            about foods you are unsure of.</p>

          <h2>Food safety and internal temperatures</h2>
          <p>Cooking times in our recipes are guides based on our equipment. Pan
            thickness, oven calibration, altitude, the starting temperature of
            the food and the size of the piece all change the outcome. Judge
            doneness by temperature, not by the clock. A probe thermometer is
            the single most useful inexpensive thing in a kitchen.</p>
          <p>Recommended minimum internal temperatures, held for the stated
            time:</p>
          <ul>
            <li><strong>Poultry</strong>, whole or pieces, and anything stuffed
              &mdash; 74&deg;C / 165&deg;F, checked at the thickest part away
              from bone.</li>
            <li><strong>Minced or ground meat</strong>, including burgers,
              meatballs and sausages &mdash; 71&deg;C / 160&deg;F throughout.
              Mince cannot be served pink.</li>
            <li><strong>Whole cuts of beef, lamb and pork</strong> &mdash;
              63&deg;C / 145&deg;F followed by a three-minute rest.</li>
            <li><strong>Fish</strong> &mdash; 63&deg;C / 145&deg;F, or until it
              flakes and is opaque throughout.</li>
            <li><strong>Leftovers and reheated dishes</strong> &mdash; 74&deg;C
              / 165&deg;F, piping hot all the way through, reheated once
              only.</li>
            <li><strong>Eggs</strong> &mdash; cook until white and yolk are firm
              if serving anyone pregnant, very young, elderly or
              immunocompromised, unless the eggs carry a recognised safety mark
              for raw consumption.</li>
          </ul>
          <p>Cool cooked food quickly, refrigerate within two hours (one hour in
            hot weather), keep your fridge at or below 5&deg;C / 41&deg;F, store
            raw meat below ready-to-eat food, and use separate boards for raw
            meat and everything else. Dried and canned pulses, particularly red
            kidney beans, must be boiled hard for at least ten minutes before
            simmering.</p>

          <h2>Raw, fermented and preserved foods</h2>
          <p>Where a recipe involves fermenting, curing, canning or preserving,
            follow the quantities and timings exactly. Salt percentages and
            acidity levels in those recipes are safety measures, not seasoning
            preferences, and reducing them can be genuinely dangerous.</p>


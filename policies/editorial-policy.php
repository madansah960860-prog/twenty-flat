          <h1>Editorial policy</h1>
          <p class="%(L)s">How recipes on this site are developed, tested,
            written and corrected &mdash; and who is responsible for each
            one.</p>
          <p><strong>Effective date:</strong> %(EFF)s.</p>

          <h2>Who writes it</h2>
          <p>Every recipe here is developed, cooked and timed by Marco Vasquez-Reid, who spent nine years in professional kitchens. Every recipe and article carries a byline and a
            publication date. We do not publish anonymously, we do not use a
            generic house name to hide who developed a dish, and we do not
            publish machine-generated recipes presented as tested work.</p>
          <p>We do not accept guest posts, sponsored recipes or outside
            contributions, and we do not sell placements in any list or
            round-up.</p>

          <h2>Every recipe is cooked</h2>
          <p>Every recipe is cooked and timed at least five times, at least twice by somebody who did not write it, with a stopwatch started when the first ingredient is picked up. The published number is the slowest of those runs rounded up, never the fastest.</p>
          <p>Testing means the whole recipe, from the written text, in a
            domestic kitchen with domestic equipment &mdash; not a
            demonstration, not a memory of having made something similar. Where
            a recipe needs a specific piece of equipment we say so, and where a
            workaround exists we give it.</p>
          <p>Quantities are recorded in grams as we cook, and cup measures are
            converted afterwards from those weights rather than the other way
            round. Where a conversion is awkward we round to the nearest sane
            kitchen measure and say what the gram figure is, because that is the
            one that will give you our result.</p>

          <h2>What we will not do</h2>
          <p>We do not republish other people&rsquo;s recipes. Where a dish is
            traditional and belongs to a cuisine rather than to a person, we say
            where our version comes from and how it differs from the version we
            were taught. Where we have adapted a specific published recipe, we
            name the original and link to it. A list of ingredients cannot be
            copyrighted; the work of writing a method can be, and more to the
            point taking it would be shabby.</p>
          <p>We do not exaggerate. A recipe described as fifteen minutes has
            been cooked in fifteen minutes, from a normal fridge, by someone
            chopping at a normal speed. We do not describe a dish as
            &ldquo;healthy&rdquo;, and we make no claims about any food curing,
            preventing or treating a medical condition.</p>

          <h2>Nutrition and allergens</h2>
          <p>Nutrition figures are calculated from standard composition data for
            the ingredients as written and are labelled as estimates on every
            recipe. Allergen notes cover the recipe as written. The limits of
            both, and why you must still read the label on the packet, are set
            out in our <a href="disclaimer.php">disclaimer</a>.</p>

          <h2>Corrections</h2>
          <p>Recipes go wrong in public, which is one of the better things about
            them: if a quantity is out, somebody cooks it and tells us. Email
            <a href="mailto:%(E)s">%(E)s</a> with the recipe name and what
            happened &mdash; what you did, what it did, and what your oven or
            hob is like if that seems relevant.</p>
          <p>We re-test before changing anything. If the recipe is wrong we
            correct it and add a dated note on the page saying what changed, so
            that anyone who cooked the old version understands why theirs
            behaved differently. We do not silently edit a method and pretend it
            always said that. An error that could make someone ill &mdash; an
            unsafe temperature, a missing allergen, a dangerous preserving ratio
            &mdash; is corrected the same day.</p>

          <h2>Independence</h2>
          <p>No advertiser, brand or affiliate partner sees a recipe before it
            is published, and none has any right to approve, change or veto
            anything here. No ingredient, brand or piece of equipment is
            recommended because somebody paid for it. How the site is funded is
            set out in full in the
            <a href="advertising-disclosure.php">advertising
            disclosure</a>.</p>


          <h2>What "15 minutes" means here</h2>
          <p>It means fifteen minutes from a cold pan to food on a plate, timed
            with a stopwatch, by somebody who has the ingredients in front of
            them and is chopping at a normal domestic speed.</p>
          <p>It does not mean fifteen minutes of cooking after forty minutes of
            preparation. It does not assume pre-chopped onions, a sous chef, or
            that the rice is already made &mdash; where a recipe needs cold
            cooked rice, that is in the ingredients and the recipe says so.</p>
          <p>Three of the six are ten minutes. Two are fifteen. One is twenty
            and it is the only one that uses the oven.</p>
          <p>Each recipe is timed at least five times, and at least twice by
            somebody who did not write it. The number published is the slowest
            of those runs rounded up, never the fastest, because the person who
            invented a dish is always quicker at it than the person reading
            about it.</p>
          <p>One recipe has had its time revised upwards since publication. The
            chilli paneer went from twelve minutes to fifteen after three
            readers in a row reported that the paneer took longer to colour
            than we had allowed for. That correction is noted on its page.</p>
        </div>
        <div class="prose">
          <h2>Six recipes, and why not sixty</h2>
          <p>Because every one has been cooked and timed at least five times,
            and because a site that publishes three new recipes a week cannot
            possibly be doing that. Four more are being timed now and at least
            one of them will be cut for going over twenty minutes.</p>
          <p>The six here cover the three situations that actually come up: no
            shopping done, a bit of shopping done, and the oven is free.</p>

          <h2>What is not here</h2>
          <p>No 800-word story before the ingredients. No "quick" recipes that
            take fifty minutes. No recipes that require a specialist shop.
            Everything on this site can be bought in a normal supermarket on
            the way home.</p>
          <p>There is also no attempt to claim any of this is healthy. It is
            dinner. Some of it has a lot of butter in it.</p>
          <p>And no step that says "meanwhile, prepare the sauce" without
            telling you when to start it. Where two things overlap, the recipe
            says so in the step itself, because that overlap is exactly where
            twenty minutes turns into thirty-five for somebody cooking it for
            the first time.</p>
        </div>
      </div>
    </div>
